LEGAL_BASIS: Dict[str, CauseLegalBasis] = {
    CAUSE_TRADEMARK: _TRADEMARK,
    CAUSE_COPYRIGHT: _COPYRIGHT,
    CAUSE_UNFAIR_COMPETITION: _UNFAIR,
}


# ============================================================
# 对外接口
# ============================================================

def get_legal_basis(cause_type: str) -> CauseLegalBasis:
    """
    取案由法律依据。

    未知案由**抛异常**而不是返回空表：静默回落的后果是拿商标的规则去评一个
    著作权案件，输出的每个数字都看似合理、实则全错，且不会有任何报错。
    """
    basis = LEGAL_BASIS.get((cause_type or "").strip())
    if basis is None:
        raise ValueError(
            f"不支持的案由：{cause_type}；当前支持 {SUPPORTED_CAUSE_TYPES}")
    return basis


def detect_level_upgrade(cause_type: str,
                         case_description: str = "") -> Optional[Tuple[str, str]]:
    """
    检测案情里是否出现会导致**级别管辖跃迁**的特殊客体。

    同一案由下客体不同，一审法院层级完全不同：
        著作权里的计算机软件 → 知识产权法院 / 省会城市中院（而非基层法院）
        不正当竞争里的技术秘密 → 同上
        商标里的驰名商标认定 → 知识产权法院 / 中级人民法院

    这个差异直接影响诉讼成本、审理周期和法官专业度，属于诉前就该提示的内容。
    """
    text = case_description or ""
    if not text:
        return None
    for keyword, upgraded in get_legal_basis(cause_type).level_upgrade:
        if keyword in text:
            return keyword, upgraded
    return None


def _join(items, indent: str = "") -> str:
    """列表条目；indent 用于把子项缩进成父项的下一级，否则渲染出来是同级兄弟"""
    return "\n".join(f"{indent}- {item}" for item in items)


def damages_clause(cause_type: str) -> str:
    """判赔规模节点的案由专属基准"""
    b = get_legal_basis(cause_type)
    return f"""## 本案由赔偿基准（{b.cause_type}）
- 计算顺位：{b.damage_order}
- 法定赔偿区间：{b.statutory_range}
- 惩罚性赔偿：{b.punitive}
- 适用注意：{b.statutory_caveat}
- 依据：{"；".join(b.sources)}

估算要求：法定赔偿区间是**边界而非预期值**，实务判赔通常远低于区间上限。
- 若本案适用法定赔偿：P10/P50/P90 须全部落在上述区间内，并以类案判赔水平为锚。
- 若本案不适用法定赔偿（见上条适用注意）：须基于实际损失或侵权获利举证推算，
  并在 analysis 中写明走的是哪个计算顺位、证据是否足以支撑该顺位。"""


def procedure_clause(cause_type: str, case_description: str = "") -> str:
    """诉讼程序节点的案由专属基准"""
    b = get_legal_basis(cause_type)
    upgrade = detect_level_upgrade(cause_type, case_description)
    if upgrade:
        level = f"{b.jurisdiction_level}；**但案情提及「{upgrade[0]}」，{upgrade[1]}**"
    else:
        level = b.jurisdiction_level
    return f"""## 本案由程序性基准（{b.cause_type}）
- 诉讼时效：{b.limitation}
- 地域管辖：{b.jurisdiction_venue}
- 级别管辖：{level}
- 前置程序：{b.preconditions}
- 本案由常见抗辩：
{_join(b.defenses, indent="  ")}
- 依据：{"；".join(b.sources)}

须逐项评估上述抗辩在本案成立的可能性——抗辩成立的，相关评分不得给高分。"""


def precedent_clause(cause_type: str) -> str:
    """判例价值节点的案由专属基准"""
    b = get_legal_basis(cause_type)
    return f"""## 本案由判例价值的判断重点（{b.cause_type}）
{_join(b.precedent_focus)}"""
