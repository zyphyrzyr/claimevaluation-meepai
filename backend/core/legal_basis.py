"""
案由法律依据表：三案由在「赔偿 / 时效 / 管辖 / 前置程序 / 常见抗辩」上的实质差异

为什么单独成模块：
    这些是**事实性基准**，不是模型判断。此前它们要么散落在 prompt 字符串里，
    要么干脆缺失——判赔规模节点让模型「结合法定赔偿区间」估算，却没告诉它本案由
    的区间是多少，模型只能凭印象填一个数。

    单独成表后：改一条法条只改这一处；每个数字都能被测试钉住；演示时被人追问
    「这个 500 万是哪来的」可以直接翻出处字段。

只进 prompt，不参与评分计算。评分仍由各节点的 LLM 完成。

法条数字来源（2026-08 查证）：
    著作权法第五十四条；商标法第五十九、六十三、六十四条；
    反不正当竞争法第六、九、十一、十二、十七条；民法典第一百八十八条；
    法释〔2020〕19号（商标民事纠纷解释）第十八条；
    法释〔2022〕13号（一审知产案件管辖规定）第一、二、三条；
    法释〔2026〕18号（著作权民事纠纷解释第二次修正，2026-09-01 施行）第三、二十二、二十三、二十五条。
"""

from dataclasses import dataclass
from typing import Dict, Optional, Tuple

from .config import (CAUSE_COPYRIGHT, CAUSE_TRADEMARK,
                     CAUSE_UNFAIR_COMPETITION, SUPPORTED_CAUSE_TYPES)


@dataclass(frozen=True)
class CauseLegalBasis:
    """某一案由的法定基准。字段值按「可直接拼进 prompt」的口径写。"""

    cause_type: str

    # —— 赔偿 ——
    # 计算顺位：法定赔偿是最后手段，前面顺位能算清就不能直接跳到法定赔偿
    damage_order: str
    statutory_range: str
    statutory_caveat: str
    punitive: str

    # —— 程序 ——
    limitation: str
    jurisdiction_venue: str
    jurisdiction_level: str

    # （客体关键词, 跃迁后的管辖）—— 同一案由下客体不同，级别管辖可能完全不同
    level_upgrade: Tuple[Tuple[str, str], ...]
    preconditions: str
    defenses: Tuple[str, ...]

    # —— 判例价值：各案由「什么才算有价值的判例」标准不同 ——
    precedent_focus: Tuple[str, ...]

    sources: Tuple[str, ...]


