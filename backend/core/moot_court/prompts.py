def get_cause_profile(cause_type: str) -> dict:
    """
    取案由画像。

    未知案由抛 ValueError 而非回落到商标——静默回落会让「选了著作权却跑出商标庭审」
    这类问题在演示时才暴露，必须在数据入口就拦下来。
    """
    if cause_type not in CAUSE_PROFILES:
        raise ValueError(
            f"不支持的案由：{cause_type}；当前支持 {SUPPORTED_CAUSE_TYPES}")
    return CAUSE_PROFILES[cause_type]


_ROLE_SYSTEM_BASE = {}  # 在三个 SYSTEM 常量定义后回填，见文件末尾


def build_system_prompt(role: str, cause_type: str) -> str:
    """角色系统提示词 + 该案由下的画像（plaintiff / defendant / judge）"""
    if role not in _ROLE_SYSTEM_BASE:
        raise ValueError(f"未知角色：{role}")
    return _ROLE_SYSTEM_BASE[role] + "\n\n" + get_cause_profile(cause_type)[role]

