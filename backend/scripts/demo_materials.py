"""
固化演示素材（三案由 × 双业务目标）

为什么要把演示素材固化成文件，而不是演示现场随手填：

1. `evidence_review` 的判定完全交给 LLM，而 `missing_rights_proof` /
   `missing_infringement_proof` 是 **block 级**红线。现场随手填一段案情，
   LLM 一旦判得偏严（9 项取证清单里没有一项被判 sufficient），流程会被
   门禁整个拦死，一个评分都出不来——这是演示事故，不是「效果偏差」。
2. 固化之后同一份输入可以反复跑，输出可比对。现场观众问「再跑一遍还是
   这个结论吗」，答案是确定的。

每份证据材料都逐条覆盖 `core/evidence_review.py` 里对应案由的取证清单，
确保三个关键类别（权利基础 / 侵权认定 / 损害赔偿）下都至少有一项能被判为
sufficient —— 这正是 `build_evidence_checklist` 给出 `has_*_proof=True` 的
唯一条件（该类别下存在任一 status == "sufficient" 的条目）。

另外注意 `check_missing_infringement_proof` 除了看证据矩阵，还会检查
案情描述里有没有「公证」二字（没有则降级 warning）。所以每份案情描述
都刻意写了「公证」；改文案时别把它删掉。

【被告名字为什么必须用真实存在的企业】
企查查回款能力是按名字去查真实工商 / 司法数据的，虚构名字必然张冠李戴。
2026-09-03 实测：

    广州锦云服饰有限公司（虚构）→ 模糊锁定「广州锦云服装有限公司」（已注销）
                              → 一票否决 → 回款 0% → 业务预期 0.0 → 总分 0.0
    林承宇（虚构自然人）        → 匹配到同名真人（失信 + 限高）→ 回款 6%
    浙江森马服饰股份有限公司    → 精确锁定，回款 78%，无红灯
    顾家家居股份有限公司        → 精确锁定，回款 78%，无红灯
    农夫山泉股份有限公司        → 精确锁定，回款 50%，无红灯

「要钱」路径的回款能力是唯一一个能把整条业务预期打成 0 的输入，而报告界面
只显示一个分数，看不出是谁干的。所以三个案由的被告都取真实、可精确匹配的
企业名；换名字前请先跑一遍确认锁定主体与红灯信号。

本模块只被 scripts/ 下的脚本引用，不进产品代码。
"""
