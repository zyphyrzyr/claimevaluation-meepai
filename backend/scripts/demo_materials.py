@dataclass(frozen=True)
class DemoCase:
    """一份可直接喂给 Orchestrator 的固化演示用例。"""
    key: str                 # 稳定标识，用于日志与落盘文件名
    label: str               # 人类可读标签
    cause_type: str
    goal_type: str           # 要钱 / 要名
    case_description: str
    evidence_texts: str
    plaintiff_name: str
    defendant_name: str
    defendant_type: str = "enterprise"

    def parties(self) -> List[Dict[str, str]]:
        return [
            {"role": "plaintiff", "name": self.plaintiff_name, "party_type": "法人"},
            {"role": "defendant", "name": self.defendant_name, "party_type": "企业"},
        ]

    def defendant_info(self) -> Dict[str, object]:
        # evidence_texts 是 evidence_review 的唯一输入，走 ctx.defendant_info；
        # name/type 供企查查画像（仅「要钱」路径回款能力会用到）。
        return {
            "name": self.defendant_name,
            "type": self.defendant_type,
            "evidence_texts": self.evidence_texts,
        }

    def with_defendant(self, name: str, type_: str = "enterprise") -> "DemoCase":
        """换一个被告（企查查链路验证用），其余字段不变。"""
        return replace(self, defendant_name=name, defendant_type=type_)


