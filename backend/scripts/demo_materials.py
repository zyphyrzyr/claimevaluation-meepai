DEMO_CASES: List[DemoCase] = []
for _cause in _CAUSES:
    for _goal in _GOALS:
        DEMO_CASES.append(DemoCase(
            key=f"{_cause}-{_goal}",
            label=f"{_cause} / {_goal}",
            cause_type=_cause,
            goal_type=_goal,
            case_description=(
                _DESCRIPTION_BY_CAUSE[_cause].format(defendant=_DEFENDANTS[_cause])
                + _GOAL_TAIL[_goal]),
            evidence_texts=EVIDENCE_BY_CAUSE[_cause],
            plaintiff_name=_PLAINTIFFS[_cause],
            defendant_name=_DEFENDANTS[_cause],
        ))

DEMO_CASES_BY_KEY: Dict[str, DemoCase] = {c.key: c for c in DEMO_CASES}


def pick(keys: str) -> List[DemoCase]:
    """按逗号分隔的 key 取用例；key 不存在直接抛错（不静默回落）。"""
    wanted = [k.strip() for k in keys.split(",") if k.strip()]
    unknown = [k for k in wanted if k not in DEMO_CASES_BY_KEY]
    if unknown:
        raise KeyError(f"未知演示用例 {unknown}；可用：{sorted(DEMO_CASES_BY_KEY)}")
    return [DEMO_CASES_BY_KEY[k] for k in wanted]


